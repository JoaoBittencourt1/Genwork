-- One row per pull request, kept current from webhook deliveries. Title, state, author, and github_updated_at are null
-- only for pull requests linked before snapshots existed. Pull requests are never removed, so there is no deleted_at.
CREATE TABLE github_pull_requests (
    id                bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    token             text NOT NULL UNIQUE,
    repository        text NOT NULL,
    number            integer NOT NULL CHECK (number > 0),
    title             text,
    state             text CHECK (state IN ('open', 'draft', 'merged', 'closed')),
    author_login      text,
    author_avatar_url text,
    github_updated_at timestamptz,
    created_at        timestamptz NOT NULL,
    updated_at        timestamptz NOT NULL,
    UNIQUE (repository, number)
);

-- The module has no 128-bit random generator in SQL, so each migrated pull request reuses the smallest token of its
-- links, which were generated by the service and never exposed.
INSERT INTO github_pull_requests (token, repository, number, created_at, updated_at)
SELECT min(token), repository, pull_request_number, min(created_at), max(updated_at)
FROM task_pull_requests
GROUP BY repository, pull_request_number;

ALTER TABLE task_pull_requests ADD COLUMN pull_request_id bigint REFERENCES github_pull_requests (id);

UPDATE task_pull_requests
SET pull_request_id = github_pull_requests.id
FROM github_pull_requests
WHERE github_pull_requests.repository = task_pull_requests.repository
  AND github_pull_requests.number = task_pull_requests.pull_request_number;

